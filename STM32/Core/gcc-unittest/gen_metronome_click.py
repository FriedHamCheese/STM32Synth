"""Generate the 12 kHz signed-8-bit metronome click array."""

from __future__ import annotations

import argparse
import math


def build_click(
    sample_rate: int,
    duration_ms: float,
    frequency_hz: float,
    amplitude: int,
    decay_ms: float,
    fade_out_ms: float,
) -> list[int]:
    count = int(round(sample_rate * duration_ms / 1000.0))
    fade_out_start = count - int(round(sample_rate * fade_out_ms / 1000.0))
    decay_samples = max(1.0, sample_rate * decay_ms / 1000.0)

    samples: list[int] = []
    for n in range(count):
        envelope = math.exp(-n / decay_samples)
        value = amplitude * envelope * math.sin(
            2.0 * math.pi * frequency_hz * n / sample_rate
        )
        if n >= fade_out_start:
            value *= (count - 1 - n) / max(1, count - 1 - fade_out_start)
        samples.append(max(-128, min(127, int(round(value)))))
    return samples


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sample-rate", type=int, default=12000)
    parser.add_argument("--duration-ms", type=float, default=30.0)
    parser.add_argument("--frequency-hz", type=float, default=1600.0)
    parser.add_argument("--amplitude", type=int, default=100)
    parser.add_argument("--decay-ms", type=float, default=8.0)
    parser.add_argument("--fade-out-ms", type=float, default=2.0)
    parser.add_argument("--out", default="-", help="Output path, or - for stdout")
    args = parser.parse_args()

    samples = build_click(
        args.sample_rate,
        args.duration_ms,
        args.frequency_hz,
        args.amplitude,
        args.decay_ms,
        args.fade_out_ms,
    )

    lines = [
        "/* Generated by gen_metronome_click.py; do not edit by hand. */",
        "#ifndef METRONOME_CLICK_H",
        "#define METRONOME_CLICK_H",
        "",
        "#include <stdint.h>",
        "",
        "static const int8_t metronome_click[] = {",
    ]
    for start in range(0, len(samples), 12):
        chunk = ", ".join(f"{value:4d}" for value in samples[start:start + 12])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        "#endif",
        "",
    ]
    text = "\n".join(lines)

    if args.out == "-":
        print(text, end="")
    else:
        with open(args.out, "w", encoding="utf-8") as out_file:
            out_file.write(text)
        print(f"Wrote {len(samples)} samples to {args.out}")


if __name__ == "__main__":
    main()
